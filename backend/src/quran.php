function normalize_arabic(string $value): string
{
    $value = trim($value);
    $value = preg_replace('/^سورة\s+/u', '', $value) ?? $value;
    $value = str_replace(['إ','أ','آ','ٱ','ى','ـ'], ['ا','ا','ا','ا','ي',''], $value);
    $value = preg_replace('/[\x{064B}-\x{065F}\x{0670}]/u', '', $value) ?? $value;
    return preg_replace('/\s+/u', ' ', $value) ?? $value;
}

function find_surah(?string $value): ?array
{
    if (!$value) return null;
    $needle = normalize_arabic($value);
    foreach (quran_surahs() as $surah) {
        if (normalize_arabic($surah['name']) === $needle) return $surah;
    }
    return null;
}

function assert_ayah_in_surah(string $surahName, int $ayah, string $label = 'الآية'): array
{
    $surah = find_surah($surahName);
    if (!$surah) app_error("السورة غير معروفة: {$surahName}", 400, 'INVALID_SURAH');
    if ($ayah < 1 || $ayah > $surah['ayahCount']) {
        app_error("{$label} في سورة {$surah['name']} يجب أن تكون بين 1 و{$surah['ayahCount']}", 400, 'INVALID_AYAH');
    }
    return $surah;
}
